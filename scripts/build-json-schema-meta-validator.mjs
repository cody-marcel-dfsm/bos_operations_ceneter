import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const output = join(
  root,
  "source/platform/bos-app-discovery/scripts/validate-json-schema-2020-12.mjs"
);
const checkOnly = process.argv.includes("--check");

const ajv = new Ajv2020({
  allErrors: true,
  strict: false,
  validateFormats: false,
  code: { source: true, esm: true }
});
const metaSchema = ajv.getSchema("https://json-schema.org/draft/2020-12/schema");
if (!metaSchema) throw new Error("Draft 2020-12 meta-schema is unavailable");

const runtimeEqual = "const func0 = require(\"ajv/dist/runtime/equal\").default;";
const embeddedEqual = `const func0 = (left, right) => {
  if (left === right) return true;
  if (!left || !right || typeof left !== "object" || typeof right !== "object") return false;
  if (Array.isArray(left) !== Array.isArray(right)) return false;
  if (Array.isArray(left)) {
    return left.length === right.length && left.every((value, index) => func0(value, right[index]));
  }
  const leftKeys = Object.keys(left);
  const rightKeys = Object.keys(right);
  return leftKeys.length === rightKeys.length &&
    leftKeys.every((key) => Object.hasOwn(right, key) && func0(left[key], right[key]));
};`;

const generated = standaloneCode(ajv, metaSchema);
if (!generated.includes(runtimeEqual)) {
  throw new Error("Ajv standalone output no longer has the expected equality runtime marker");
}
const content = [
  "// Generated by scripts/build-json-schema-meta-validator.mjs. Do not edit by hand.",
  generated.replace(runtimeEqual, embeddedEqual),
  ""
].join("\n");

if (checkOnly) {
  const current = await readFile(output, "utf8").catch(() => "");
  if (current !== content) {
    throw new Error("Generated Draft 2020-12 meta-validator is stale");
  }
} else {
  await writeFile(output, content, "utf8");
}
